// Builds the Hype art for the store from the sources in brand/hype/art:
//   crest-<rank>.webp  -> public/hype/crest-<rank>-{160,384}.webp (trimmed, faint haze cleared)
//   frame-<name>.webp  -> public/hype/frame-<name>-{400,800}.webp, and the frame's opening
// and writes lib/hype-art.ts with each frame's opening (fractions of the frame),
// so the product photo sits exactly inside it. Usage: node scripts/hype-art.mjs
import sharp from 'sharp'
import { readdirSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SRC = 'brand/hype/art'
const OUT = 'public/hype'
mkdirSync(OUT, { recursive: true })

/** Pixels with alpha at or below this become fully transparent (clears generated haze and soft shadows). */
const HAZE = 40

async function cleaned(file) {
  const { data, info } = await sharp(join(SRC, file)).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  for (let i = 3; i < data.length; i += 4) if (data[i] <= HAZE) data[i] = 0
  return { data, info }
}

/** The frame's opening: from the centre outwards along rows and columns clear of the centre ornaments, to the first solid pixel. */
function opening({ data, info }) {
  const { width: w, height: h } = info
  const solid = (x, y) => data[(y * w + x) * 4 + 3] > 128
  // Rows through the middle find the sides; columns are then placed inside the opening, clear of the
  // corners (wings) and the centre (halos, medallions), to find the top and bottom.
  const rows = [0.4, 0.45, 0.5, 0.55, 0.6].map((f) => Math.round(h * f))
  const left = Math.min(...rows.map((y) => { let x = Math.round(w / 2); while (x > 0 && !solid(x, y)) x--; return x }))
  const right = Math.max(...rows.map((y) => { let x = Math.round(w / 2); while (x < w - 1 && !solid(x, y)) x++; return x }))
  const cols = [0.3, 0.4, 0.6, 0.7].map((f) => Math.round(left + (right - left) * f))
  const top = Math.min(...cols.map((x) => { let y = Math.round(h / 2); while (y > 0 && !solid(x, y)) y--; return y }))
  const bottom = Math.max(...cols.map((x) => { let y = Math.round(h / 2); while (y < h - 1 && !solid(x, y)) y++; return y }))
  // The border's outer edge on the same lines: past the solid pixels to the next clear one.
  const out = (x0, y0, dx, dy) => { let x = x0, y = y0; while (x > 0 && x < w - 1 && y > 0 && y < h - 1 && solid(x, y)) { x += dx; y += dy } return dx ? x : y }
  const edgeLeft = Math.min(...rows.map((y) => out(left, y, -1, 0)))
  const edgeRight = Math.max(...rows.map((y) => out(right, y, 1, 0)))
  const edgeTop = Math.min(...cols.map((x) => out(x, top, 0, -1)))
  const edgeBottom = Math.max(...cols.map((x) => out(x, bottom, 0, 1)))
  // Reach a little under the border so no gap shows between photo and frame.
  const pad = Math.round(w * 0.012)
  const r = (n) => Math.round(n * 10000) / 10000
  return {
    aspect: r(h / w),
    x: r((left - pad) / w), y: r((top - pad) / h), w: r((right - left + 2 * pad) / w), h: r((bottom - top + 2 * pad) / h),
    edge: { x: r(edgeLeft / w), y: r(edgeTop / h), w: r((edgeRight - edgeLeft) / w), h: r((edgeBottom - edgeTop) / h) },
  }
}

const openings = {}
for (const file of readdirSync(SRC).filter((f) => f.endsWith('.webp')).sort()) {
  const name = file.replace('.webp', '')
  const img = await cleaned(file)
  const raw = () => sharp(img.data, { raw: img.info })
  if (name.startsWith('crest-')) {
    const trimmed = await raw().trim({ threshold: 1 }).png().toBuffer()
    for (const size of [160, 384]) {
      await sharp(trimmed).resize(size, size, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
        .webp({ quality: 86, alphaQuality: 90 }).toFile(join(OUT, `${name}-${size}.webp`))
    }
  } else {
    openings[name.replace('frame-', '')] = opening(img)
    for (const width of [400, 800]) {
      await raw().resize(width).webp({ quality: 84, alphaQuality: 90 }).toFile(join(OUT, `${name}-${width}.webp`))
    }
  }
  console.log(name)
}

writeFileSync('lib/hype-art.ts', `// Generated by scripts/hype-art.mjs from brand/hype/art: don't edit by hand.
// Each frame's opening (where the product photo goes) and its border's outer
// edge (fitted to the card), as fractions of the frame from the top left, and
// the frame image's height over width.
// Wings, halos and medallions reach outside the edge.
type Box = { x: number; y: number; w: number; h: number }
export const FRAME_OPENINGS: Record<string, Box & { aspect: number; edge: Box }> = ${JSON.stringify(openings, null, 2)}
`)
console.log(openings)
